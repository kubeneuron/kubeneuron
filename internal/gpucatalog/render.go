// Generated-artifact paths, relative to the repository root. The generator
// writes them; verify-gpucatalog asserts they equal a fresh render.
const (
	PathYAML     = "config/gpu-metrics/catalog.yaml"
	PathCSV      = "config/gpu-metrics/dcgm-fields.csv"
	PathMarkdown = "docs/reference-gpu-metrics.md"
)

const header = "generated by `make generate-gpucatalog` from internal/gpucatalog; do not edit"

// Render returns every generated artifact keyed by path. Output is a pure
// function of the catalog: no timestamps, stable ordering.
func Render(c Catalog) (map[string][]byte, error) {
	if err := c.Validate(); err != nil {
		return nil, err
	}
	y, err := renderYAML(c)
	if err != nil {
		return nil, err
	}
	out := map[string][]byte{
		PathYAML:     y,
		PathCSV:      renderCSV(c),
		PathMarkdown: renderMarkdown(c),
	}
	boards, err := renderDashboards()
	if err != nil {
		return nil, err
	}
	for p, b := range boards {
		out[p] = b
	}
	return out, nil
}

// yamlField is Field with the support map flattened to a sorted list, so the
// encoder's output order is explicit instead of map-order dependent.
type yamlField struct {
	Field   `yaml:",inline"`
	Support []yamlSupport `yaml:"support,omitempty"`
}

type yamlSupport struct {
	Hardware Hardware `yaml:"hardware"`
	Status   Support  `yaml:"status"`
}

type yamlCatalog struct {
	Version           string          `yaml:"version"`
	CanonicalContract string          `yaml:"canonical_contract"`
	Fields            []yamlField     `yaml:"fields"`
	ReservedCanonical []Reservation   `yaml:"reserved_canonical"`
	XIDBuckets        []XIDBucket     `yaml:"xid_buckets"`
	Deferred          []Deferral      `yaml:"deferred"`
	Derived           []DerivedSignal `yaml:"derived"`
}

func renderYAML(c Catalog) ([]byte, error) {
	out := yamlCatalog{Version: c.Version, CanonicalContract: c.CanonicalContract, ReservedCanonical: c.ReservedCanonical, XIDBuckets: c.XIDBuckets, Deferred: c.Deferred, Derived: c.Derived}
	for _, f := range c.Fields {
		yf := yamlField{Field: f}
		yf.Field.Support = nil
		for _, hw := range allHardware {
			if s, ok := f.Support[hw]; ok {
				yf.Support = append(yf.Support, yamlSupport{Hardware: hw, Status: s})
			}
		}
		out.Fields = append(out.Fields, yf)
	}
	var buf bytes.Buffer
	fmt.Fprintf(&buf, "# %s\n", header)
	buf.WriteString("# Each field has a source side (dcgm_field, aliases, series, exporter_exposed, source, raw) and a\n")
	buf.WriteString("# canonical side (canonical.series/kind/unit/factor/labels). See canonical_contract: the canonical\n")
	buf.WriteString("# side is the contract the shipped recording rules implement: the canonical series is recorded\n")
	buf.WriteString("# from the source series when the source exists and is absent otherwise; recording it validates nothing.\n")
	fmt.Fprintf(&buf, "# source is %s only for fields the shipped exporter profile lists (exporter_exposed: true);\n", SourceDCGMExporter)
	fmt.Fprintf(&buf, "# source %s marks a DCGM field that is merely cataloged and that no exporter is asserted to emit.\n", SourceDCGMField)
	fmt.Fprintf(&buf, "# derived lists the signals the %s* recording groups compute from canonical series, or from derived series declared earlier (formula = the rule expr);\n", DerivedGroupPrefix)
	buf.WriteString("# no_data says what an absent sample means, and an entry with deferred set is intentionally not recorded.\n")
	enc := yaml.NewEncoder(&buf)
	enc.SetIndent(2)
	if err := enc.Encode(out); err != nil {
		return nil, err
	}
	if err := enc.Close(); err != nil {
		return nil, err
	}
	return buf.Bytes(), nil
}

// canonicalCell renders the canonical side of a field for the CSV and the
// per-field Markdown rows.
func canonicalCell(f Field) string {
	if f.Canonical == nil {
		return "none (" + f.CanonicalDeferred + ")"
	}
	k := f.Canonical
	s := k.Series + k.LabelSet()
	if len(k.ValueLabels) > 0 {
		s += "{" + strings.Join(k.ValueLabels, ",") + " decoded}"
	}
	return s
}

// CSVReferenceNotice is the banner the generated CSV carries so it cannot be
// mistaken for an exporter profile or for an inventory of emitted fields. It
// is data, not prose, so the tests can assert the artifact says it.
const CSVReferenceNotice = "REFERENCE ONLY. This is NOT a dcgm-exporter metrics profile and NOT an inventory of emitted fields: " +
	"do not mount it, and do not read a row here as proof that anything emits the field. " +
	"Only rows with profiled=yes and source=" + string(SourceDCGMExporter) + " are listed in the shipped profile; " +
	"every row with profiled=no and source=" + string(SourceDCGMField) + " is cataloged from NVIDIA documentation and no exporter is asserted to emit it."

// renderCSV emits the DCGM fields in dcgm-exporter's metrics-config format
// (FIELD, type, help). It is a reference artifact: the shipped
// gpu-operator values are NOT regenerated from it in this milestone, and
// the format is borrowed for familiarity, not so the file can be mounted.
// The help column carries the honest source, the series name the pinned
// exporter would use and the canonical series the shipped recording rules
// derive from it.
func renderCSV(c Catalog) []byte {
	var buf bytes.Buffer
	fmt.Fprintf(&buf, "# %s\n", header)
	fmt.Fprintf(&buf, "# %s\n", CSVReferenceNotice)
	buf.WriteString("# Format: DCGM FIELD, Prometheus metric type, help message\n")
	fmt.Fprintf(&buf, "# %s is not derived from this file and this file is not derived from it.\n", ShippedProfilePath)
	buf.WriteString("# `profiled` is yes only when the shipped profile lists the series, so the pinned dcgm-exporter is configured to emit it.\n")
	fmt.Fprintf(&buf, "# `source` is %s for those rows and %s for every other row (cataloged only, emission not asserted).\n", SourceDCGMExporter, SourceDCGMField)
	buf.WriteString("# `series` is the series name the exporter uses for the id when it does emit it (a legacy name where DCGM renamed the field).\n")
	fmt.Fprintf(&buf, "# `canonical` is the kubeneuron_gpu_* series the recording rules (%s) derive from the row's series:\n", CanonicalRulePath)
	buf.WriteString("# recorded when the source series exists, absent otherwise, and no evidence of hardware support either way.\n")
	buf.WriteString("# Cataloged-only (deferred) fields are listed as comments: no profile enables them and nothing acts on them.\n")
	for _, f := range c.Fields {
		if f.DCGMFieldID == 0 {
			continue
		}
		profiled := "no"
		if f.ExporterExposed {
			profiled = "yes"
		}
		help := fmt.Sprintf("[%s][%d] %s | profiled=%s | source=%s | series=%s | canonical=%s",
			f.Tier, f.DCGMFieldID, strings.ReplaceAll(f.Help, "\n", " "), profiled, f.Source, f.Series, canonicalCell(f))
		if f.Deferred != "" {
			fmt.Fprintf(&buf, "# deferred: %s, %s, %s\n", f.DCGMField, f.Kind, help)
			continue
		}
		fmt.Fprintf(&buf, "%s, %s, %s\n", f.DCGMField, f.Kind, help)
	}
	return buf.Bytes()
}

func renderMarkdown(c Catalog) []byte {
	var b strings.Builder
	fmt.Fprintf(&b, "<!-- %s -->\n", header)
	fmt.Fprintf(&b, "# GPU metric catalog %s\n\n", c.Version)
	b.WriteString("Canonical catalog of the GPU and control-plane signals KubeNeuron recognises. ")
	b.WriteString("It describes signals only: no alert rule, detector threshold, playbook or controller behaviour is derived from it.\n\n")
	b.WriteString("Every DCGM entry has a **source side** (the DCGM field id and name, the legacy names the id has carried, the series the pinned dcgm-exporter uses, whether the shipped profile lists it, the raw unit) ")
	b.WriteString("and a **canonical side** (the `kubeneuron_gpu_*` series it feeds, the canonical unit and factor, and the fixed labels that merge several DCGM fields into one canonical metric).\n\n")
	fmt.Fprintf(&b, "> **Contract, not inventory.** %s\n\n", c.CanonicalContract)
	b.WriteString("Tiers have fixed meanings: **T0** baseline GPU telemetry, **T1** GPU reliability telemetry, ")
	b.WriteString("**T2** DCGM effective-work / profiling telemetry (deferred, no entries), **T3** serving / Triton telemetry (deferred, no entries), ")
	b.WriteString("**T4** KubeNeuron control-plane telemetry. Tier T4 is the control plane and is unrelated to the Tesla T4 GPU, which is a hardware column. ")
	b.WriteString("Hardware support is a separate dimension; `validated` means a recorded run of this project observed the value, and every such cell cites its evidence; ")
	b.WriteString("`not-applicable` is asserted only where NVIDIA documentation establishes the feature is absent, otherwise a cell is `unknown`. ")
	b.WriteString("No v0.7 hardware validation has been performed; `declared` cells are unvalidated.\n\n")
	b.WriteString("Units: `raw` is what the source emits; `canonical` is the normalised unit with `canonical = raw × factor` (a decode, marked `decoded`, has no factor). ")
	fmt.Fprintf(&b, "`Profiled` is `yes` only when the shipped exporter profile (%s) lists the source series, so the pinned exporter is configured to emit it; ", ShippedProfilePath)
	b.WriteString("every other field is cataloged from NVIDIA documentation and no exporter is asserted to emit it. ")
	fmt.Fprintf(&b, "`Source` says the same thing as a value: `%s` exactly for the profiled fields, `%s` for a field that is merely cataloged. ", SourceDCGMExporter, SourceDCGMField)
	b.WriteString("`Source series` is the name the exporter uses for the id when it does emit it, which is the legacy DCGM name where DCGM renamed the field; the current DCGM name is accepted as an alias on exporter builds that know it. ")
	b.WriteString("A cataloged-only entry is marked deferred and is enabled in no profile, read by no rule and attached to no action.\n\n")

	for _, tier := range []Tier{TierT0, TierT1} {
		fmt.Fprintf(&b, "## Tier %s (DCGM)\n\n", tier)
		b.WriteString("| DCGM field id | DCGM field | Source | Source series | Profiled | Kind | Raw unit | Canonical series | Canonical unit | Factor |")
		for _, hw := range allHardware {
			fmt.Fprintf(&b, " %s |", hw)
		}
		b.WriteString(" Help |\n")
		b.WriteString("|---|---|---|---|---|---|---|---|---|---|")
		for range allHardware {
			b.WriteString("---|")
		}
		b.WriteString("---|\n")
		for _, f := range c.Fields {
			if f.Tier != tier {
				continue
			}
			name := f.DCGMField
			if len(f.Aliases) > 0 {
				name += " (legacy: " + strings.Join(f.Aliases, ", ") + ")"
			}
			series := "`" + f.Series + "`"
			if len(f.SeriesAliases) > 0 {
				series += " (alias `" + strings.Join(f.SeriesAliases, "`, `") + "`)"
			}
			profiled := "no"
			if f.ExporterExposed {
				profiled = "yes"
			}
			canonSeries, canonUnit, factor := "—", "—", "—"
			if f.Canonical != nil {
				canonSeries = "`" + canonicalCell(f) + "`"
				canonUnit = string(f.Canonical.Unit)
				factor = "decoded"
				if len(f.Canonical.ValueLabels) == 0 {
					factor = formatFactor(f.Canonical.Factor)
				}
			}
			fmt.Fprintf(&b, "| %d | `%s` | %s | %s | %s | %s | %s | %s | %s | %s |", f.DCGMFieldID, name, f.Source, series, profiled, f.Kind, f.Raw.Unit, canonSeries, canonUnit, factor)
			for _, hw := range allHardware {
				fmt.Fprintf(&b, " %s |", f.Support[hw])
			}
			help := f.Help
			if f.Canonical == nil {
				help += " No canonical series: " + f.CanonicalDeferred + "."
			}
			if f.Deferred != "" {
				help += " Deferred: " + f.Deferred + "."
			}
			fmt.Fprintf(&b, " %s |\n", help)
		}
		b.WriteString("\n")
	}
	for _, tier := range DeferredTiers {
		fmt.Fprintf(&b, "## Tier %s\n\nDeferred: no entries. See Deferred below.\n\n", tier)
	}

	b.WriteString("## Tier T4 (KubeNeuron control plane)\n\n")
	b.WriteString("Existing `kubeneuron_*` series registered by internal/metrics; the catalog adds none and each is its own canonical series. Label sets are in docs/reference-metrics.md.\n\n")
	b.WriteString("| Series | Source | Kind | Unit | Help |\n|---|---|---|---|---|\n")
	for _, f := range c.Fields {
		if f.Tier != TierT4 {
			continue
		}
		fmt.Fprintf(&b, "| `%s` | %s | %s | %s | %s |\n", f.Series, f.Source, f.Kind, f.Canonical.Unit, f.Help)
	}

	b.WriteString("\n## Canonical series (recording-rule contract)\n\n")
	b.WriteString("One row per `kubeneuron_gpu_*` series, with every DCGM field that feeds it and the fixed labels that keep the rows apart. ")
	fmt.Fprintf(&b, "`Profiled sources` names the feeding fields the shipped exporter profile lists today (source `%s`); a series whose sources are all unprofiled (source `%s`) has no input until the profile changes. ", SourceDCGMExporter, SourceDCGMField)
	fmt.Fprintf(&b, "The recording rules in `%s` (mirrored in the deployed VMRule) record every series below from its profiled sources with the stated factor and labels; a series exists exactly when a source is scraped, and recording it is not evidence that any hardware reports the source. The derived signals below read these series. The only alerts that read any of them are the shadow-only ShadowGpu* rules (`configs/vmalert/gpu-shadow-rules.yaml`), which route to humans and trigger no remediation; no controller-facing alert reads a canonical series.\n\n", CanonicalRulePath)
	b.WriteString("| Canonical series | Kind | Unit | Labels | Sources (DCGM field id: source series → labels) | Profiled sources | Notes |\n|---|---|---|---|---|---|---|\n")
	for _, series := range c.CanonicalSeries() {
		rows := c.LookupCanonical(series)
		if rows[0].Tier == TierT4 {
			continue
		}
		k := rows[0].Canonical
		labels := make([]string, 0, len(k.Labels)+len(k.ValueLabels))
		for _, l := range k.Labels {
			labels = append(labels, l.Name)
		}
		for _, v := range k.ValueLabels {
			labels = append(labels, v+" (decoded)")
		}
		labelCell := strings.Join(labels, ", ")
		if labelCell == "" {
			labelCell = "—"
		}
		var srcs, profiled, notes []string
		for _, f := range rows {
			srcs = append(srcs, fmt.Sprintf("%d: `%s` → %s", f.DCGMFieldID, f.Series, selectorOrNone(f.Canonical)))
			if f.ExporterExposed {
				profiled = append(profiled, fmt.Sprint(f.DCGMFieldID))
			}
			if f.Canonical.Note != "" {
				notes = append(notes, f.Canonical.Note)
			}
		}
		profiledCell := "none"
		if len(profiled) > 0 {
			profiledCell = strings.Join(profiled, ", ")
		}
		noteCell := "—"
		if len(notes) > 0 {
			noteCell = strings.Join(dedupe(notes), "; ")
		}
		fmt.Fprintf(&b, "| `%s` | %s | %s | %s | %s | %s | %s |\n", series, k.Kind, k.Unit, labelCell, strings.Join(srcs, "; "), profiledCell, noteCell)
	}

	b.WriteString("\n## Derived signals\n\n")
	fmt.Fprintf(&b, "Series the `%s*` recording groups in `%s` (mirrored in the deployed VMRule) compute from canonical series, Tier T4 control-plane series or derived series declared earlier in this table. ", DerivedGroupPrefix, CanonicalRulePath)
	b.WriteString("`Formula` is the rule expression verbatim; `Inputs` are the canonical series, Tier T4 control-plane series or earlier derived series it reads, and nothing reads a dcgm-exporter series directly. ")
	b.WriteString("`No data` states what an absent sample means: no formula uses `or vector(0)`, `default` or `absent()`, so a derived series is missing when an input its formula needs at that instant is missing or a divisor guard (`> 0`) excludes the sample, never replaced by a fabricated zero. Which inputs a formula needs is stated per row: most rows need every input, while the thermal headroom needs either the margin or both fallback inputs (slowdown threshold and temperature) and is missing only when neither is reported. ")
	b.WriteString("`Carried` labels flow through from the input; fixed labels are added by the rule. Each series is one component: there is deliberately no aggregate health or error score, because one number would hide which component moved. The only score in the table is the experimental fail-slow peer score, which compares one device to its peers and sums no components. ")
	b.WriteString("A row may read a derived series declared above it (the fail-slow score reads the clock and throttle ratios); table order is evaluation order. Rows marked experimental are shadow signals whose formula may change: they are read only by the Fail-slow Radar board and the shadow-only ShadowGpuFailSlow alert, which triggers no remediation, and by no controller path. Recording a derived series is not evidence that any hardware reports its inputs.\n\n")
	b.WriteString("| Derived series | Kind | Unit | Fixed labels | Carried | Group | Inputs | Formula | No data | Help |\n|---|---|---|---|---|---|---|---|---|---|\n")
	for _, d := range c.Derived {
		if d.Deferred != "" {
			continue
		}
		labels := d.LabelSet()
		if labels == "" {
			labels = "—"
		} else {
			labels = "`" + labels + "`"
		}
		carried := "—"
		if len(d.Carried) > 0 {
			carried = strings.Join(d.Carried, ", ")
		}
		inputs := make([]string, 0, len(d.Inputs))
		for _, in := range d.Inputs {
			inputs = append(inputs, "`"+in+"`")
		}
		help := d.Help
		if d.Experimental {
			help += " Experimental: the formula may change before anything relies on it."
		}
		fmt.Fprintf(&b, "| `%s` | %s | %s | %s | %s | `%s` | %s | `%s` | %s | %s |\n", d.Series, d.Kind, d.Unit, labels, carried, d.Group, strings.Join(inputs, ", "), strings.ReplaceAll(d.Formula, "|", "\\|"), d.NoData, help)
	}
	b.WriteString("\n### Derived signals intentionally not recorded\n\n")
	b.WriteString("These series are No data by design: no rule records them, and the reason is stated so the gap is not mistaken for a missing rule.\n\n")
	for _, d := range c.Derived {
		if d.Deferred != "" {
			fmt.Fprintf(&b, "- `%s` (%s, %s): %s %s\n", d.Series, d.Kind, d.Unit, d.Help, d.Deferred)
		}
	}

	b.WriteString("\n### DCGM fields with no canonical series\n\n")
	for _, f := range c.Fields {
		if f.DCGMFieldID != 0 && f.Canonical == nil {
			fmt.Fprintf(&b, "- %d `%s`: %s.\n", f.DCGMFieldID, f.Series, f.CanonicalDeferred)
		}
	}

	b.WriteString("\n### Reserved canonical names\n\n")
	b.WriteString("Names the brief defines that no cataloged source may claim yet. The validator rejects any mapping to them.\n\n")
	for _, r := range c.ReservedCanonical {
		fmt.Fprintf(&b, "- `%s`: %s\n", r.Series, r.Reason)
	}

	b.WriteString("\n## Evidence\n\n")
	for _, f := range c.Fields {
		if f.Evidence != "" {
			fmt.Fprintf(&b, "- `%s`: %s\n", f.Series, f.Evidence)
		}
	}
	b.WriteString("\n## Shipped consumers\n\n")
	fmt.Fprintf(&b, "Files and components whose expressions or code read the source series today. This is a claim independent of `Profiled`: the exporter profile (%s) is never listed here, and a profiled series with no reader is a legitimate state (the profile can list a series before any rule reads it). Since v1.6.0 every profiled series is read by the canonical recording rules (`%s`, mirrored in `%s`); only the nine v0.6.1 series are also read by the legacy raw alerts (`%s`).\n\n", ShippedProfilePath, CanonicalRulePath, DeployedRulePath, LegacyRulePath)
	for _, f := range c.Fields {
		if len(f.ConsumedBy) > 0 {
			fmt.Fprintf(&b, "- `%s`: %s\n", f.Series, strings.Join(f.ConsumedBy, ", "))
		}
	}

	b.WriteString("\n## XID buckets\n\n")
	b.WriteString("Bounded label values for `xid_bucket`. A bucket names the reporting subsystem, never an action.\n\n")
	b.WriteString("| Bucket | Codes | Help |\n|---|---|---|\n")
	for _, bk := range c.XIDBuckets {
		codes := make([]string, 0, len(bk.Codes))
		for _, code := range bk.Codes {
			codes = append(codes, fmt.Sprint(code))
		}
		cs := strings.Join(codes, ", ")
		if cs == "" {
			cs = "(all others)"
		}
		fmt.Fprintf(&b, "| `%s` | %s | %s |\n", bk.Name, cs, bk.Help)
	}

	b.WriteString("\n## Deferred\n\n")
	for _, d := range c.Deferred {
		fmt.Fprintf(&b, "- **%s** — %s\n", d.Area, d.Reason)
	}
	return []byte(b.String())
}

func selectorOrNone(k *Canonical) string {
	if s := k.LabelSet(); s != "" {
		return "`" + s + "`"
	}
	if len(k.ValueLabels) > 0 {
		return "decoded " + strings.Join(k.ValueLabels, ", ")
	}
	return "(no labels)"
}

func dedupe(in []string) []string {
	seen := map[string]bool{}
	var out []string
	for _, s := range in {
		if !seen[s] {
			seen[s] = true
			out = append(out, s)
		}
	}
	return out
}

func formatFactor(f float64) string {
	switch {
	case f == 1:
		return "1"
	case f == float64(int64(f)):
		return fmt.Sprintf("%d", int64(f))
	default:
		return fmt.Sprintf("%g", f)
	}
}

// Paths returns the generated-artifact paths in stable order.
func Paths() []string {
	p := append([]string{PathYAML, PathCSV, PathMarkdown}, DashboardPaths()...)
	sort.Strings(p)
	return p
}
