"""Record the Debian packages each pinned distroless base image brings.

The licence label of an image names what KubeNeuron adds; the base image adds
Debian packages under their own licences (glibc under LGPL in the agent's
base, OpenSSL, ca-certificates, tzdata, ...). This lists them per pinned
digest and architecture, with the licences their Debian copyright files
declare and where their sources are, in build/licenses/base-image-packages.txt,
which every image ships as /licenses/BASE-IMAGE-PACKAGES.

  python3 -I hack/base-image-packages.py            regenerate (needs docker)
  python3 -I hack/base-image-packages.py --check    regenerate and compare (needs docker)
  python3 -I hack/base-image-packages.py --check-digests
                                                    the record names exactly the
                                                    digests build/Dockerfile pins (no docker)

A package whose copyright file declares no machine-readable licence and is not
in REVIEWED stops the generator: a new base-image package needs a review.
"""
import argparse
import io
import os
from pathlib import Path
import re
import subprocess
import sys
import tarfile

ROOT = Path(__file__).resolve().parents[1]
DOCKERFILE = ROOT / 'build/Dockerfile'
OUTPUT = ROOT / 'build/licenses/base-image-packages.txt'
ARCHES = ('amd64', 'arm64')
BASE = re.compile(r'^FROM\s+(gcr\.io/distroless/[^\s@]+@sha256:[0-9a-f]{64})', re.M)
# Packages whose Debian copyright file is not machine-readable: the licence
# summary was read from the file by hand; the file itself ships in the image.
REVIEWED = {
    'base-files': 'GPL-2.0-or-later',
    'glibc': 'LGPL-2.1-or-later AND others listed in /usr/share/doc/libc6/copyright',
}
DOCKER = os.environ.get('DOCKER_BIN', 'docker')


def pinned_bases():
    return sorted(set(BASE.findall(DOCKERFILE.read_text())))


def image_files(image, arch):
    """dpkg status entries and copyright files of one platform of an image."""
    cid = subprocess.check_output([DOCKER, 'create', '--platform', f'linux/{arch}', image, '/x'], text=True).strip()
    try:
        raw = subprocess.check_output([DOCKER, 'export', cid])
    finally:
        subprocess.run([DOCKER, 'rm', '-f', cid], capture_output=True)
    status, copyright = {}, {}
    with tarfile.open(fileobj=io.BytesIO(raw)) as tar:
        for member in tar.getmembers():
            name = member.name.lstrip('./')
            if name.startswith('var/lib/dpkg/status.d/') and not name.endswith('.md5sums') and member.isfile():
                status[name.rsplit('/', 1)[1]] = tar.extractfile(member).read().decode()
            elif name.startswith('usr/share/doc/') and name.endswith('/copyright') and member.isfile():
                copyright[name.split('/')[3]] = tar.extractfile(member).read().decode(errors='replace')
    return status, copyright


def field(text, key):
    match = re.search(rf'^{key}:\s*(\S+)', text, re.M)
    return match.group(1) if match else ''


def licences(package, source, copyright_text):
    declared = sorted(set(re.findall(r'^License:\s*(.+?)\s*$', copyright_text or '', re.M)))
    if declared:
        return ' AND '.join(f'({d})' if ' ' in d else d for d in declared)
    if source in REVIEWED:
        return REVIEWED[source]
    sys.exit(f'base-image-packages: {package} (source {source}) declares no licence and is not reviewed; '
             'read its copyright file and add it to REVIEWED')


def generate():
    lines = ['Generated by hack/base-image-packages.py; do not edit.',
             'Debian packages of the pinned distroless base images, with the licences their',
             'Debian copyright files declare (full texts: /usr/share/doc/<package>/copyright',
             'in the image). Sources: https://sources.debian.org/src/<source>/<version>/;',
             'older versions remain available at https://snapshot.debian.org/.',
             'We do not modify these packages. Their source code is available at the locations',
             'below; on request to hello@kubeneuron.com we will provide the source for the',
             'versions listed, for three years after the release that contains this file.',
             '']
    for image in pinned_bases():
        lines.append(f'== {image}')
        for arch in ARCHES:
            status, copyright = image_files(image, arch)
            lines.append(f'-- linux/{arch}')
            for name in sorted(status):
                entry = status[name]
                package, version = field(entry, 'Package'), field(entry, 'Version')
                source = field(entry, 'Source') or package
                lines.append(f'{package} {version} (source {source}): {licences(package, source, copyright.get(package))}')
                lines.append(f'  https://sources.debian.org/src/{source}/{version}/')
                lines.append(f'  https://snapshot.debian.org/package/{source}/{version}/')
        lines.append('')
    return '\n'.join(lines).rstrip('\n') + '\n'


def recorded_bases():
    if not OUTPUT.exists():
        return []
    return sorted(re.findall(r'^== (\S+)$', OUTPUT.read_text(), re.M))


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('--check', action='store_true')
    parser.add_argument('--check-digests', action='store_true')
    args = parser.parse_args()
    if args.check_digests:
        if recorded_bases() != pinned_bases():
            sys.exit('base-image-packages: build/licenses/base-image-packages.txt does not record the base '
                     'image digests build/Dockerfile pins; run python3 -I hack/base-image-packages.py')
        return
    content = generate()
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text() != content:
            sys.exit('base-image-packages: stale record; run python3 -I hack/base-image-packages.py')
        return
    OUTPUT.write_text(content)


if __name__ == '__main__':
    main()
