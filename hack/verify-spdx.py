"""Every source file carries an SPDX-License-Identifier that matches LICENSE.

The path rules mirror the root LICENSE file: api/, pkg/, config/, deploy/,
docs/ and examples/ are Apache-2.0; everything else is LicenseRef-KubeNeuron.
A file whose header names the wrong license fails, as does a source file
with no header.

Usage:
  hack/verify-spdx.py          check (CI, make lint)
  hack/verify-spdx.py --fix    add missing headers
"""
import os, re, subprocess, sys

APACHE = ("api/", "pkg/", "config/", "deploy/", "docs/", "examples/")
SKIP_PARTS = ("/testdata/", "/node_modules/", "vendor/")
# Generated by controller-gen with hack/boilerplate.go.txt as its header.
GENERATED = {"api/v1alpha1/zz_generated.deepcopy.go"}

def lic(path):
    return "Apache-2.0" if path.startswith(APACHE) else "LicenseRef-KubeNeuron"

def style(path):
    base = os.path.basename(path)
    if base == "Makefile" or base.startswith("Dockerfile") and not base.endswith(".dockerignore"):
        return "#"
    ext = os.path.splitext(path)[1]
    return {".go": "//", ".ts": "//", ".proto": "//", ".sh": "#", ".py": "#",
            ".tmpl": "#", ".sql": "--", ".tpl": "tpl", ".html": "html"}.get(ext)

def header(path):
    ident = "SPDX-License-Identifier: " + lic(path)
    st = style(path)
    if st == "tpl":
        return "{{/* " + ident + " */}}"
    if st == "html":
        return "<!-- " + ident + " -->"
    return st + " " + ident

def insert(path, text):
    h = header(path)
    lines = text.split("\n")
    i = 0
    st = style(path)
    if lines and lines[0].startswith("#!"):
        i = 1
    elif st == "#" and os.path.basename(path).startswith("Dockerfile"):
        # BuildKit parser directives must stay first.
        while i < len(lines) and re.match(r"^#\s*(syntax|escape|check)\s*=", lines[i]):
            i += 1
    elif st == "html" and lines and lines[0].lower().startswith("<!doctype"):
        i = 1
    block = [h]
    if st in ("//", "--", "#") and i < len(lines) and lines[i].strip() != "":
        block.append("")
    return "\n".join(lines[:i] + block + lines[i:])

def main():
    repo = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    check = "--fix" not in sys.argv
    files = subprocess.run(["git", "-C", repo, "ls-files"], capture_output=True, text=True, check=True).stdout.split()
    files += subprocess.run(["git", "-C", repo, "ls-files", "--others", "--exclude-standard"], capture_output=True, text=True, check=True).stdout.split()
    missing, wrong, changed = [], [], 0
    for path in sorted(set(files)):
        full = os.path.join(repo, path)
        if not os.path.isfile(full) or style(path) is None or path in GENERATED:
            continue
        if any(part in "/" + path for part in SKIP_PARTS):
            continue
        text = open(full, encoding="utf-8").read()
        head = "\n".join(text.split("\n")[:5])
        m = re.search(r"SPDX-License-Identifier: (\S+)", head)
        if m:
            if m.group(1).rstrip("*/->}").strip() != lic(path) and m.group(1) != lic(path):
                wrong.append((path, m.group(1)))
            continue
        missing.append(path)
        if not check:
            open(full, "w", encoding="utf-8").write(insert(path, text))
            changed += 1
    for p, got in wrong:
        print(f"WRONG {p}: {got}, want {lic(p)}")
    if check:
        for p in missing:
            print(f"MISSING {p}")
        if missing or wrong:
            print("verify-spdx: FAILED — run hack/verify-spdx.py --fix (wrong headers need a manual fix)")
            sys.exit(1)
        print("verify-spdx: ok")
        sys.exit(0)
    print(f"verify-spdx: added headers to {changed} files")
    sys.exit(1 if wrong else 0)

main()
